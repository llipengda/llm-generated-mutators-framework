MANIFEST_NAME = "mutator_manifest.json"
MANIFEST_VERSION = 1
GENERATED_HEADER = "// Generated by core.mutator_codegen. Do not edit.\n"
Operation = Literal["Add", "Remove", "Repeat", "Mutate"]
_MANIFEST_LOCK = RLock()


@dataclass(frozen=True)
class SemanticHook:
    name: str
    signature: str


@dataclass(frozen=True)
class MutatorSpec:
    packet_type: str
    path: str
    operation: Operation
    class_name: str
    namespace: str
    base_class: str
    expression: str
    empty_branch_name: str | None
    description: str
    hooks: tuple[SemanticHook, ...]
    runtime_type: str
    kind: str
    dsl_path: str | None
    condition: ExprResult | None
    source_path: str | None
    enabled: bool = True


@dataclass(frozen=True)
class PacketMutatorPlan:
    packet_type: str
    generated_file: Path
    semantic_file: Path
    output_dll: Path
    mutators: tuple[MutatorSpec, ...]


@dataclass(frozen=True)
class MutatorPlan:
    protocol: str
    dsl_dir: Path
    output_dir: Path
    packets: tuple[PacketMutatorPlan, ...]


class _ClassRecord(TypedDict):
    class_name: str
    operation: str
    path: str
    base_class: str
    hooks: list[str]
    namespace: str
    expression: str
    empty_branch_name: str | None
    description: str
    runtime_type: str
    kind: str
    dsl_path: str | None
    source_path: str | None
    enabled: bool


class _PacketRecord(TypedDict):
    generated_file: str
    semantic_file: str
    output_dll: str
    classes: list[_ClassRecord]


class _Manifest(TypedDict):
    version: int
    protocol: str
    dsl_dir: str
    active_packets: list[str]
    packets: dict[str, _PacketRecord]


def _object(value: object, context: str) -> dict[str, object]:
    if not isinstance(value, dict):
        raise ValueError(f"{context} must be an object")
    return cast(dict[str, object], value)


def _array(value: object, context: str) -> list[object]:
    if not isinstance(value, list):
        raise ValueError(f"{context} must be a list")
    return cast(list[object], value)


def _string(value: object, context: str) -> str:
    if not isinstance(value, str) or not value:
        raise ValueError(f"{context} must be a nonempty string")
    return value


def _optional_string(value: object, context: str) -> str | None:
    if value is None:
        return None
    if not isinstance(value, str):
        raise ValueError(f"{context} must be a string or null")
    return value


def _hash_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _excluded_sdk_references() -> list[str]:
    """Keep copied protocol and test artifacts out of mutator compilation."""
    return sorted(path.name for path in peach_sdk_dir().glob("*.dll") if path.name not in MUTATOR_SDK_REFERENCE_NAMES)


def _packet_choices(dsl_dir: Path, protocol: str) -> list[tuple[str, str, str | None]]:
    raw: object = json.loads((dsl_dir / "schema_manifest.json").read_text(encoding="utf-8"))
    manifest = _object(raw, "schema manifest")
    if str(manifest.get("protocol", "")).casefold() != protocol.casefold():
        raise ValueError("schema manifest protocol does not match")
    result: list[tuple[str, str, str | None]] = []
    seen_packets: set[str] = set()
    used_choices: set[str] = set()
    for group in _array(manifest.get("packet_groups"), "packet_groups"):
        models = _array(_object(group, "packet group").get("packet_models"), "packet_models")
        for raw_model in models:
            model = _object(raw_model, "packet model")
            packet = _string(model.get("packet_type"), "packet_type")
            if packet.casefold() in seen_packets:
                raise ValueError(f"duplicate packet type: {packet}")
            seen_packets.add(packet.casefold())
            choice = packet_choice_name(packet)
            if choice in used_choices:
                suffix = 2
                while f"{choice}_{suffix}" in used_choices:
                    suffix += 1
                choice = f"{choice}_{suffix}"
            used_choices.add(choice)
            legacy_choice = model.get("choice_name")
            result.append((packet, choice, legacy_choice if isinstance(legacy_choice, str) else None))
    if not result:
        raise ValueError("schema manifest has no packet models")
    return result


def _operations(node: MutationNode) -> tuple[Operation, ...]:
    if node.node_type & (NodeType.FIXED | NodeType.DERIVED) or not node.node_type & NodeType.MUTABLE:
        return ()
    operations: list[Operation] = []
    if node.node_type & NodeType.OPTIONAL:
        operations.extend(("Add", "Remove"))
    if node.node_type & NodeType.REPEATABLE:
        operations.append("Repeat")
    operations.append("Mutate")
    return tuple(operations)


def _bounded_identifier(value: str, limit: int = 180) -> str:
    """Keep DLL and validator log basenames below filesystem name limits."""
    if len(value) <= limit:
        return value
    return value[:limit - 9] + "_" + hashlib.sha256(value.encode()).hexdigest()[:8]


def build_mutator_plan(
    protocol: str, *, dsl_dir: Path | None = None, output_dir: Path | None = None,
    packet_types: Sequence[str] | None = None,
) -> MutatorPlan:
    protocol = normalize_identifier(protocol)
    directory = (dsl_dir or Path("llm/peach") / protocol / "datamodel_dsl").resolve()
    destination = (output_dir or Path("llm/peach") / protocol / "Mutators").resolve()
    choices = _packet_choices(directory, protocol)
    selected = {packet.casefold() for packet in packet_types} if packet_types is not None else None
    if selected is not None:
        unknown = selected - {packet.casefold() for packet, _, _ in choices}
        if unknown:
            raise ValueError("packet types absent from DSL manifest: " + ", ".join(sorted(unknown)))
    root = load_dsl_root(directory / "root.py")
    nodes = get_mutation_nodes(root, name=root.__name__)
    plans: list[PacketMutatorPlan] = []
    filenames: set[str] = set()
    for packet, choice, legacy_choice in choices:
        if selected is not None and packet.casefold() not in selected:
            continue
        candidates = {
            node.path for node in nodes
            if node.path.endswith(f".packet_union.{choice}")
        }
        if not candidates and legacy_choice:
            candidates = {
                node.path for node in nodes
                if node.path.endswith(f".packet_union.{legacy_choice}")
            }
        if len(candidates) != 1:
            raise ValueError(f"cannot identify unique PacketUnion alternative for {packet}: {sorted(candidates)}")
        packet_path = next(iter(candidates))
        stem = _bounded_identifier(protocol.upper() + normalize_symbol(packet) + "Mutators")
        if stem.casefold() in filenames:
            raise ValueError(f"packet types produce the same C# filename: {stem}")
        filenames.add(stem.casefold())
        namespace = f"Peach.LLM.Generated.Mutators.{protocol.upper()}.{normalize_symbol(packet)}"
        specs: list[MutatorSpec] = []
        class_names: set[str] = set()
        for node in nodes:
            if not node.path.startswith(packet_path + "."):
                continue
            relative = node.path[len(packet_path) + 1:]
            field_name = normalize_symbol(relative.replace("[]", "Item"))
            for operation in _operations(node):
                base = "LLMMutator" if operation == "Mutate" else f"LLM{operation}Mutator"
                expression = supported_data_element_expression(node.path)
                if operation != "Mutate":
                    extra = ", " + _csharp_string(node.empty_branch_name) if node.empty_branch_name and operation in ("Add", "Remove") else ""
                    expression += f" && {base}.CanApply(obj{extra})"
                hooks: tuple[SemanticHook, ...] = ()
                if operation == "Mutate":
                    hooks = (SemanticHook("MutateCore", "private void MutateCore(DataElement obj)"),)
                elif operation in ("Add", "Remove"):
                    if node.runtime_type == "Optional":
                        hooks = (SemanticHook("UpdatePresenceSource", "protected override partial void UpdatePresenceSource(Peach.LLM.Core.Dom.Optional optional, bool exists)"),)
                    if operation == "Add":
                        hooks = (SemanticHook("InitializeAddedContent", "protected override void InitializeAddedContent(DataElement content)"), *hooks)
                stem_name = (protocol.upper() + normalize_symbol(packet) + operation + field_name)[:180]
                class_name = stem_name
                suffix = 2
                while class_name.casefold() in class_names:
                    ending = f"_{suffix}"
                    class_name = stem_name[:180 - len(ending)] + ending
                    suffix += 1
                class_names.add(class_name.casefold())
                specs.append(MutatorSpec(
                    packet, node.path, operation,
                    class_name,
                    namespace, base, expression, node.empty_branch_name,
                    node.description, hooks, node.runtime_type, node.kind, node.dsl_path,
                    node.condition, node.source_path,
                ))
        plans.append(PacketMutatorPlan(packet, destination / (stem + ".g.cs"), destination / (stem + ".semantic.cs"), destination / "out" / (stem + ".dll"), tuple(specs)))
    return MutatorPlan(protocol, directory, destination, tuple(plans))


def render_plan_yaml(plan: MutatorPlan) -> str:
    """Compact review view; executable contracts are still derived from the DSL."""
    groups: list[tuple[list[str], dict[str, list[Operation]], dict[str, str]]] = []
    for packet in plan.packets:
        targets: dict[str, list[Operation]] = {}
        presence_sources: dict[str, str] = {}
        for spec in packet.mutators:
            # Strip the root, PacketUnion and packet alternative from each path.
            prefix, separator, relative = spec.path.partition(".packet_union.")
            alternative, dot, relative = relative.partition(".")
            if not separator or not dot:
                raise ValueError(f"Cannot locate packet-relative target: {spec.path}")
            rooted_prefix = prefix + separator + alternative + dot
            targets.setdefault(relative, []).append(spec.operation)
            if any(hook.name == "UpdatePresenceSource" for hook in spec.hooks):
                if spec.source_path is None:
                    raise ValueError(f"Conditional target has no presence source: {spec.path}")
                presence_sources[relative] = spec.source_path.removeprefix(rooted_prefix)
        for packets, existing_targets, existing_sources in groups:
            if targets == existing_targets and presence_sources == existing_sources:
                packets.append(packet.packet_type)
                break
        else:
            groups.append(([packet.packet_type], targets, presence_sources))

    # JSON-quoted strings are valid YAML scalars, including paths with [] and
    # packet names such as ON that YAML could otherwise interpret as booleans.
    def quote(value: str) -> str:
        return json.dumps(value, ensure_ascii=False)

    lines = [
        "# Generated review plan. Field details and method signatures come from the DSL and SDK.",
        "# presence_sources marks targets requiring UpdatePresenceSource for Add/Remove.",
        f"protocol: {quote(plan.protocol)}",
        "groups:" if groups else "groups: []",
    ]
    for packets, targets, presence_sources in groups:
        lines.append("  - packets: [" + ", ".join(quote(packet) for packet in packets) + "]")
        lines.append("    targets:" if targets else "    targets: {}")
        for path, operations in targets.items():
            lines.append(f"      {quote(path)}: [{', '.join(operations)}]")
        if presence_sources:
            lines.append("    presence_sources:")
            for path, source in presence_sources.items():
                lines.append(f"      {quote(path)}: {quote(source)}")
    return "\n".join(lines) + "\n"


def _csharp_string(value: str) -> str:
    return '@"' + value.replace('"', '""') + '"'


def render_generated(packet: PacketMutatorPlan) -> str:
    lines = [GENERATED_HEADER.rstrip(), "using System.ComponentModel;", "using Peach.Core;", "using Peach.Core.Dom;", "using Peach.LLM.Core;", "using Peach.LLM.Core.Mutators;", ""]
    if not packet.mutators:
        return "\n".join(lines) + "\n"
    lines.extend([f"namespace {packet.mutators[0].namespace}", "{"])
    for spec in packet.mutators:
        extra = ", " + _csharp_string(spec.empty_branch_name) if spec.empty_branch_name and spec.operation in ("Add", "Remove") else ""
        selector = spec.expression
        if spec.operation == "Mutate":
            selector += " && (obj is not Peach.LLM.Core.Dom.Optional optional || optional.Exists)"
        lines.extend([
            f"    [Mutator({_csharp_string(spec.class_name)})]",
            f"    [Description({_csharp_string(spec.operation + ' ' + spec.path)})]",
            f"    public partial class {spec.class_name} : {spec.base_class}", "    {",
            f"        public {spec.class_name}(DataElement obj) : base(obj{extra}) {{ }}",
            f"        public new static bool supportedDataElement(DataElement obj) => {selector if spec.enabled else 'false'};",
        ])
        if spec.operation == "Mutate":
            lines.append("        protected override void PerformMutation(DataElement obj) => MutateCore(obj);")
        for hook in spec.hooks:
            if hook.name == "UpdatePresenceSource":
                lines.append(f"        {hook.signature};")
        lines.extend(["    }", ""])
    lines.append("}")
    return "\n".join(lines) + "\n"


def render_semantic_stub(packet: PacketMutatorPlan) -> str:
    """Create declarations only; missing required methods must fail compilation."""
    lines = ["// Implement the required semantic functions in these partial classes.", "using System;", "using Peach.Core;", "using Peach.Core.Dom;", "using Peach.LLM.Core;", "using Peach.LLM.Core.Mutators;", ""]
    if not packet.mutators:
        return "\n".join(lines) + "\n"
    lines.extend([f"namespace {packet.mutators[0].namespace}", "{"])
    for spec in packet.mutators:
        if spec.hooks:
            lines.extend([f"    public partial class {spec.class_name}", "    {"])
            lines.extend(f"        // REQUIRED: {hook.signature}" for hook in spec.hooks)
            lines.extend(["    }", ""])
    lines.append("}")
    return "\n".join(lines) + "\n"


@contextmanager
def _locked(directory: Path) -> Generator[None]:
    directory.mkdir(parents=True, exist_ok=True)
    with _MANIFEST_LOCK, (directory / ".mutator_manifest.lock").open("a") as lock:
        fcntl.flock(lock.fileno(), fcntl.LOCK_EX)
        try:
            yield
        finally:
            fcntl.flock(lock.fileno(), fcntl.LOCK_UN)


def _atomic_text(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", encoding="utf-8", dir=path.parent, prefix=path.name + ".", delete=False) as temporary:
        temporary.write(content)
        temporary_path = Path(temporary.name)
    try:
        os.replace(temporary_path, path)
    finally:
        temporary_path.unlink(missing_ok=True)


def _managed_path(directory: Path, filename: str, suffix: str) -> Path:
    pattern = r"[A-Za-z][A-Za-z0-9_]*" + re.escape(suffix)
    if suffix == ".dll":
        pattern = "out/" + pattern
    if not re.fullmatch(pattern, filename):
        raise ValueError(f"invalid managed source/artifact path: {filename!r}")
    path = directory / filename
    if not path.resolve().is_relative_to(directory.resolve()):
        raise ValueError(f"managed path escapes output directory: {filename!r}")
    return path


def _legacy_empty_branch(directory: Path, generated: str, class_name: str) -> str | None:
    """Recover the constructor argument omitted by the original v1 records."""
    source = _managed_path(directory, generated, ".g.cs")
    if not source.is_file():
        return None
    match = re.search(
        re.escape(class_name) + r'\(DataElement obj\)\s*:\s*base\(obj,\s*@"((?:[^"]|"")*)"\)',
        source.read_text(encoding="utf-8"),
    )
    return match.group(1).replace('""', '"') if match else None


def _read_manifest(directory: Path) -> _Manifest | None:
    path = directory / MANIFEST_NAME
    if not path.is_file():
        return None
    raw: object = json.loads(path.read_text(encoding="utf-8"))
    manifest = _object(raw, "mutator manifest")
    if manifest.get("version") != MANIFEST_VERSION:
        raise ValueError("unsupported mutator manifest version")
    protocol = _string(manifest.get("protocol"), "protocol")
    if normalize_identifier(protocol) != protocol:
        raise ValueError("invalid manifest protocol")
    dsl_dir = _string(manifest.get("dsl_dir"), "dsl_dir")
    packets: dict[str, _PacketRecord] = {}
    for packet, raw_entry in _object(manifest.get("packets"), "packets").items():
        entry = _object(raw_entry, f"packet {packet}")
        generated = _string(entry.get("generated_file"), "generated_file")
        semantic = _string(entry.get("semantic_file"), "semantic_file")
        output = _string(entry.get("output_dll"), "output_dll")
        _managed_path(directory, generated, ".g.cs")
        _managed_path(directory, semantic, ".semantic.cs")
        _managed_path(directory, output, ".dll")
        classes: list[_ClassRecord] = []
        for raw_class in _array(entry.get("classes"), "classes"):
            cls = _object(raw_class, "class")
            hooks = [_string(hook, "hook") for hook in _array(cls.get("hooks"), "hooks")]
            operation = _string(cls.get("operation"), "operation")
            if operation not in ("Add", "Remove", "Repeat", "Mutate"):
                raise ValueError(f"invalid mutator operation: {operation}")
            target = _string(cls.get("path"), "path")
            base = _string(cls.get("base_class"), "base_class")
            class_name = _string(cls.get("class_name"), "class_name")
            enabled = cls.get("enabled", True)
            if not isinstance(enabled, bool):
                raise ValueError("mutator enabled must be a boolean")
            empty_branch = _optional_string(cls.get("empty_branch_name"), "empty_branch_name") if "empty_branch_name" in cls else _legacy_empty_branch(directory, generated, class_name)
            expression = supported_data_element_expression(target)
            if operation != "Mutate":
                extra = ", " + _csharp_string(empty_branch) if empty_branch and operation in ("Add", "Remove") else ""
                expression += f" && {base}.CanApply(obj{extra})"
            classes.append({
                "class_name": class_name,
                "operation": operation, "path": target, "base_class": base, "hooks": hooks,
                "namespace": _string(cls.get("namespace", f"Peach.LLM.Generated.Mutators.{protocol.upper()}.{normalize_symbol(packet)}"), "namespace"),
                "expression": _string(cls.get("expression", expression), "expression"),
                "empty_branch_name": empty_branch,
                "description": _optional_string(cls.get("description", ""), "description") or "",
                "runtime_type": _optional_string(cls.get("runtime_type", ""), "runtime_type") or "",
                "kind": _optional_string(cls.get("kind", ""), "kind") or "",
                "dsl_path": _optional_string(cls.get("dsl_path"), "dsl_path"),
                "source_path": _optional_string(cls.get("source_path"), "source_path"),
                "enabled": enabled,
            })
        # Older v1 manifests included build fingerprints. They are ignored and
        # omitted when the host next writes the manifest.
        packets[packet] = {"generated_file": generated, "semantic_file": semantic, "output_dll": output, "classes": classes}
    active = [_string(packet, "active packet") for packet in _array(manifest.get("active_packets", list(packets)), "active_packets")]
    if len(active) != len(set(active)):
        raise ValueError("mutator manifest contains duplicate active packets")
    return {"version": MANIFEST_VERSION, "protocol": protocol, "dsl_dir": dsl_dir, "active_packets": active, "packets": packets}


def _manifest_for(plan: MutatorPlan) -> _Manifest:
    manifest = _read_manifest(plan.output_dir)
    if manifest is None:
        return {"version": MANIFEST_VERSION, "protocol": plan.protocol, "dsl_dir": str(plan.dsl_dir), "active_packets": [], "packets": {}}
    if manifest["protocol"] != plan.protocol or Path(manifest["dsl_dir"]).resolve() != plan.dsl_dir:
        raise ValueError("mutator manifest belongs to another protocol or DSL directory")
    return manifest


def _write_manifest(directory: Path, manifest: _Manifest) -> None:
    _atomic_text(directory / MANIFEST_NAME, json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")


def _record(plan: MutatorPlan, packet: PacketMutatorPlan) -> _PacketRecord:
    return {"generated_file": packet.generated_file.name, "semantic_file": packet.semantic_file.name, "output_dll": "out/" + packet.output_dll.name, "classes": [{
        "class_name": spec.class_name, "operation": spec.operation, "path": spec.path,
        "base_class": spec.base_class, "hooks": [hook.signature for hook in spec.hooks],
        "namespace": spec.namespace, "expression": spec.expression,
        "empty_branch_name": spec.empty_branch_name, "description": spec.description,
        "runtime_type": spec.runtime_type, "kind": spec.kind, "dsl_path": spec.dsl_path,
        "source_path": spec.source_path,
        "enabled": spec.enabled,
    } for spec in packet.mutators]}


def _class_contract(classes: list[_ClassRecord]) -> list[tuple[str, str, str, str, tuple[str, ...]]]:
    return [(cls["class_name"], cls["operation"], cls["path"], cls["base_class"], tuple(cls["hooks"])) for cls in classes]


def _assert_packet(plan: MutatorPlan, packet: PacketMutatorPlan) -> None:
    if packet not in plan.packets:
        raise ValueError("packet is not part of this mutator plan")
    for path, suffix in ((packet.generated_file, ".g.cs"), (packet.semantic_file, ".semantic.cs"), (packet.output_dll, ".dll")):
        _managed_path(plan.output_dir, path.relative_to(plan.output_dir).as_posix(), suffix)


def _archive_source(plan: MutatorPlan, source: Path) -> None:
    if not source.resolve().is_relative_to(plan.output_dir):
        raise ValueError("source archive escapes output directory")
    archive = plan.output_dir / ".archive"
    archive.mkdir(exist_ok=True)
    destination = archive / (source.name + "." + _hash_file(source)[:12] + ".bak")
    if not destination.resolve().is_relative_to(plan.output_dir):
        raise ValueError("source archive escapes output directory")
    os.replace(source, destination)


def prepare_packet(plan: MutatorPlan, packet: PacketMutatorPlan) -> None:
    _assert_packet(plan, packet)
    with _locked(plan.output_dir):
        manifest = _manifest_for(plan)
        if packet.generated_file.is_file() and not packet.generated_file.read_text(encoding="utf-8").startswith(GENERATED_HEADER):
            raise ValueError(f"refusing to overwrite unmanaged file: {packet.generated_file}")
        # Only the old framework's exact per-packet filename is migrated.
        legacy_name = plan.protocol.upper() + packet.packet_type.capitalize() + "Mutators.cs"
        legacy = plan.output_dir / legacy_name
        if len(legacy_name.encode()) <= 255 and re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*\.cs", legacy_name) and legacy.is_file():
            _archive_source(plan, legacy)
        old = manifest["packets"].get(packet.packet_type)
        if old is not None and old["semantic_file"] == packet.semantic_file.name and _class_contract(old["classes"]) != _class_contract(_record(plan, packet)["classes"]) and packet.semantic_file.is_file():
            # A changed class/path/signature set requires fresh partial
            # implementations. Preserve the previous source for inspection.
            _archive_source(plan, packet.semantic_file)
        _atomic_text(packet.generated_file, render_generated(packet))
        if not packet.semantic_file.exists():
            _atomic_text(packet.semantic_file, render_semantic_stub(packet))
        manifest["packets"][packet.packet_type] = _record(plan, packet)
        if packet.packet_type not in manifest["active_packets"]:
            manifest["active_packets"].append(packet.packet_type)
        _write_manifest(plan.output_dir, manifest)


def packet_outputs_exist(plan: MutatorPlan, packet: PacketMutatorPlan) -> bool:
    """Offer reuse when this packet's recorded sources and DLL exist."""
    _assert_packet(plan, packet)
    with _locked(plan.output_dir):
        manifest = _read_manifest(plan.output_dir)
        if manifest is None or manifest["protocol"] != plan.protocol:
            return False
        entry = manifest["packets"].get(packet.packet_type)
        if entry is None:
            return False
        paths = (
            _managed_path(plan.output_dir, entry["generated_file"], ".g.cs"),
            _managed_path(plan.output_dir, entry["semantic_file"], ".semantic.cs"),
            _managed_path(plan.output_dir, entry["output_dll"], ".dll"),
        )
        return all(path.is_file() for path in paths)


def compile_packet(plan: MutatorPlan, packet: PacketMutatorPlan) -> subprocess.CompletedProcess[str]:
    _assert_packet(plan, packet)
    if not packet.generated_file.is_file() or packet.generated_file.read_text(encoding="utf-8") != render_generated(packet):
        return subprocess.CompletedProcess([], 2, "", "Generated mutator source differs from the deterministic plan; prepare the packet first.")
    references = sorted((plan.output_dir.parent / "DataElements" / "out").glob("*DataElements.dll"))
    packet.output_dll.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".build-", dir=packet.output_dll.parent) as build_dir:
        temporary_dll = Path(build_dir) / packet.output_dll.name
        result = compile_csharp([packet.generated_file, packet.semantic_file], temporary_dll, additional_references=references, excluded_reference_names=_excluded_sdk_references())
        if result.returncode == 0:
            if not temporary_dll.is_file():
                return subprocess.CompletedProcess(result.args, 1, result.stdout, result.stderr + "\nCompiler did not produce a mutator DLL.")
            os.replace(temporary_dll, packet.output_dll)
        return result


def packet_for_class(plan: MutatorPlan, class_name: str) -> PacketMutatorPlan:
    for packet in plan.packets:
        if any(spec.class_name == class_name for spec in packet.mutators):
            return packet
    raise ValueError(f"mutator class is absent from the mutator plan: {class_name}")


def set_active_packets(plan: MutatorPlan, packet_types: Sequence[str]) -> None:
    """Select the exact packets participating in subsequent aggregate builds."""
    canonical = {packet.packet_type.casefold(): packet.packet_type for packet in plan.packets}
    unknown = {packet.casefold() for packet in packet_types} - canonical.keys()
    if unknown:
        raise ValueError("active packet types absent from plan: " + ", ".join(sorted(unknown)))
    active = list(dict.fromkeys(canonical[packet.casefold()] for packet in packet_types))
    with _locked(plan.output_dir):
        manifest = _manifest_for(plan)
        manifest["active_packets"] = active
        _write_manifest(plan.output_dir, manifest)


def disable_mutators(plan: MutatorPlan, class_names: Sequence[str]) -> MutatorPlan:
    """Persist disabled selectors while preserving every semantic interface."""
    names = set(class_names)
    known = {spec.class_name for packet in plan.packets for spec in packet.mutators}
    if names - known:
        raise ValueError("mutator classes absent from plan: " + ", ".join(sorted(names - known)))
    updated = replace(plan, packets=tuple(
        replace(packet, mutators=tuple(
            replace(spec, enabled=False) if spec.class_name in names else spec
            for spec in packet.mutators
        )) for packet in plan.packets
    ))
    with _locked(plan.output_dir):
        manifest = _manifest_for(plan)
        changed = [
            (old, new) for old, new in zip(plan.packets, updated.packets)
            if old != new
        ]
        # Validate all contracts before changing any generated source.
        for old, _ in changed:
            entry = manifest["packets"].get(old.packet_type)
            if entry != _record(plan, old) or old.generated_file.read_text(encoding="utf-8") != render_generated(old):
                raise ValueError("mutator contract changed; reload the active manifest before disabling")
        for _, packet in changed:
            _atomic_text(packet.generated_file, render_generated(packet))
            manifest["packets"][packet.packet_type] = _record(updated, packet)
        _write_manifest(plan.output_dir, manifest)
    return updated


def manifest_packet_types(output_dir: Path) -> list[str]:
    with _locked(output_dir.resolve()):
        manifest = _read_manifest(output_dir.resolve())
        if manifest is None or not manifest["active_packets"]:
            raise ValueError("no active managed mutator packets; select and generate packets in Step 4")
        return manifest["active_packets"]


def _active_sources(directory: Path, manifest: _Manifest | None) -> list[Path]:
    if manifest is None or not manifest["active_packets"]:
        raise ValueError(f"no managed mutator sources in {directory / MANIFEST_NAME}")
    missing = set(manifest["active_packets"]) - manifest["packets"].keys()
    if missing:
        raise ValueError("active mutator packets have not been prepared: " + ", ".join(sorted(missing)))
    sources: list[Path] = []
    for packet in manifest["active_packets"]:
        entry = manifest["packets"][packet]
        sources.extend((_managed_path(directory, entry["generated_file"], ".g.cs"), _managed_path(directory, entry["semantic_file"], ".semantic.cs")))
    if len(sources) != len(set(sources)) or any(not source.is_file() for source in sources):
        raise ValueError("mutator manifest contains duplicate or missing sources")
    return sorted(sources)


def manifest_sources(output_dir: Path) -> list[Path]:
    """List the existing active source pairs recorded by the host."""
    directory = output_dir.resolve()
    with _locked(directory):
        return _active_sources(directory, _read_manifest(directory))


def load_mutator_plan(output_dir: Path) -> MutatorPlan:
    """Load generated contracts for validation and repair, without reading DSL."""
    directory = output_dir.resolve()
    with _locked(directory):
        manifest = _read_manifest(directory)
        _active_sources(directory, manifest)
        assert manifest is not None
        packets: list[PacketMutatorPlan] = []
        for packet_type in manifest["active_packets"]:
            entry = manifest["packets"][packet_type]
            specs: list[MutatorSpec] = []
            for cls in entry["classes"]:
                hooks = tuple(SemanticHook(signature.split("(", 1)[0].split()[-1], signature) for signature in cls["hooks"])
                specs.append(MutatorSpec(
                    packet_type, cls["path"], cast(Operation, cls["operation"]), cls["class_name"],
                    cls["namespace"], cls["base_class"], cls["expression"], cls["empty_branch_name"],
                    cls["description"], hooks, cls["runtime_type"], cls["kind"], cls["dsl_path"],
                    None, cls["source_path"], cls["enabled"],
                ))
            packets.append(PacketMutatorPlan(
                packet_type, _managed_path(directory, entry["generated_file"], ".g.cs"),
                _managed_path(directory, entry["semantic_file"], ".semantic.cs"),
                _managed_path(directory, entry["output_dll"], ".dll"), tuple(specs),
            ))
        return MutatorPlan(manifest["protocol"], Path(manifest["dsl_dir"]).resolve(), directory, tuple(packets))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Preview DSL mutator plans or compile managed sources")
    parser.add_argument("command", choices=("plan", "compile", "sources"))
    parser.add_argument("protocol")
    parser.add_argument("--output", type=Path)
    args = parser.parse_args(argv)
    try:
        if args.command == "plan":
            # DSL modules may print their model tree on import; stdout must
            # contain only the requested YAML when used in a shell pipeline.
            with redirect_stdout(io.StringIO()):
                plan = build_mutator_plan(args.protocol)
            preview = render_plan_yaml(plan)
            if args.output:
                args.output.parent.mkdir(parents=True, exist_ok=True)
                args.output.write_text(preview, encoding="utf-8")
            else:
                print(preview, end="")
            return 0
        directory = Path("llm/peach") / normalize_identifier(args.protocol) / "Mutators"
        sources = manifest_sources(directory)
        if args.command == "sources":
            for source in sources:
                print(source)
            return 0
        output = args.output or directory / "out" / (normalize_identifier(args.protocol) + "_mutators.dll")
        references = sorted((directory.parent / "DataElements" / "out").glob("*DataElements.dll"))
        result = compile_csharp(sources, output, additional_references=references, excluded_reference_names=_excluded_sdk_references())
        print(result.stdout, end="")
        print(result.stderr, end="")
        return result.returncode
    except (OSError, ValueError, json.JSONDecodeError) as error:
        print(f"[FAIL] {error}")
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
